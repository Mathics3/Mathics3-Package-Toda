(* Definitions for working with finitely generated Abelian groups.      *)

Group::usage = 
 TeXToMath[StringJoin[
  "Group[{\\(a_1,d_1\\),...,{\\(a_n,d_n\\)}] represents the direct sum ",
  "of cyclic groups of order \\(d_i\\) generated by the elements ",
  "\\(a_i\\).  The value \\(d_i\\)=Infinity is allowed."
 ]]
CyclicFormat[{x_, Infinity}] :=
  SequenceForm[\[DoubleStruckCapitalZ], x]
CyclicFormat[{x_, n_Integer}] :=
  SequenceForm[Subscript[\(\[DoubleStruckCapitalZ]\),n], x]
Format[Group[]]    = 0
Format[Group[C_]] := CyclicFormat[C]
Format[A_Group]   := CyclicFormat /@ (CirclePlus @@ A) /; Length[A] > 1

GType::usage = 
 TeXToMath[StringJoin[
  "GType[\\(d_1\\),...,\\(d_n\\)] represents the isomorphism class of ",
  "abelian groups containing \\(\\Z_{d_1}\\oplus...\\oplus\\Z_{d_n}\\). ",
  "The \\(d_i\\) should be in nondecreasing order and may be infinite. ",
  "This should be improved to deal better with the case of groups with ",
  "torsion at more than one prime."
 ]]
Format[GType[]]  = 0
Format[GType[Infinity]]  = \[DoubleStruckCapitalZ]
Format[GType[n_Integer]] :=
 Subscript[\[DoubleStruckCapitalZ],n]
Format[GType[l__]] :=
 GType /@ CirclePlus[l] /; Length[{l}] > 1

GroupType::usage =
 "GroupType[A] is the isomorphism class of the group A."
GroupType[A_Group]      := GType @@ Sort[Last /@ (List @@ A)]
GroupType[l_List]       := GroupType /@ l

GroupOrder::usage =
 "GroupOrder[A] is the order of the group A."
GroupOrder[A_Group]     := Times @@ GroupType[A]
GroupOrder[l_List]      := GroupOrder /@ l

FiniteQ::usage =
 "FiniteQ[A] is True iff the group A is finite."
FiniteQ[A_Group]        := (GroupOrder[A] =!= Infinity)
FiniteQ[l_List]         := FiniteQ /@ l

GroupRank::usage = 
 StringJoin[
  "GroupRank[A] is the number of cyclic factors in the group A. ",
  "This should be improved to deal better with the case of groups with ",
  "torsion at more than one prime."
 ]
GroupRank[A_Group]      := Length[A]
GroupRank[l_List]       := GroupRank /@ l

GroupExponent::usage = 
 StringJoin[
  "GroupExponent[A] is the least integer \\(m\\) such that \\(ma=0\\) for ",
  "all \\(a \\in A\\), or Infinity if no such \\(m\\) exists. "
 ]
GroupExponent[A_Group] :=
 If[Length[A] == 0,
  1,
  If[Max @@ (Last /@ A) === Infinity,
     Infinity,
     LCM @@ (Last /@ A)]
 ]
GroupExponent[l_List]   := GroupExponent /@ l
Generators[A_Group]     := First /@ (List @@ A)
Generators[l_List]      := Generators /@ l

TorsionSubgroup[G_Group] := 
 Select[G,Last[#] =!= Infinity &]

pBasis[A_Group] :=
 Flatten[# (2^ Range[0,Log[2,AdditiveOrder[#]] - 1]) & /@ Generators[A]]

GroupGeneratedBy::usage = 
 TeXToMath[StringJoin[
  "GroupGeneratedBy[\\(a_1\\),...,\\(a_n\\)] gives ",
  "Group[{\\(a_1,d_1\\)},...,{\\(a_n,d_n\\)}], where ",
  "\\(d_i\\) = AdditiveOrder[\\(a_i\\)].  This is just a convenience ",
  "function for declaring groups and is not intended for use in ",
  "calculation."
 ]]
GroupGeneratedBy[gens___] := 
 Group @@ ({#,AdditiveOrder[#]} & /@ {gens})

Elements::usage = 
 "Elements[A] is the list of all elements of the finite group A."
ElementsAux[{a_,m_}]    := Table[k a,{k,0,m-1}]
Elements[Group[]] = {0}
Elements[A_Group]       := 
 Flatten[Outer @@ Join[{Plus},ElementsAux /@ List @@ A],Length[A]-1] /;
 FiniteQ[A]


(* Here is a very naive function for checking whether an element is     *)
(* is contained in a specified group.  It assumes that the generators   *)
(* are symbols, and will not work if they are linear combinations of    *)
(* symbols.                                                             *)

ElementQ[0,A_Group] := True

ElementQ[a_Plus,A_Group] := 
 And @@ (ElementQ[#,A] & /@ (List @@ a))

ElementQ[n_Integer a_,A_Group] := ElementQ[a,A]

ElementQ[l_List,A_Group] := 
 And @@ (ElementQ[#,A] & /@ l)

ElementQ[a_,A_Group] := True /; MemberQ[Generators[A],a]

ElementQ[_,A_Group] := False


 

Coset[a_,{u___,0,v___}] := Coset[a,{u,v}]
Coset /: n_Integer Coset[a_,B_List] := Coset[Expand[n a],Expand[n B]]
Coset[a_,{}] := a

