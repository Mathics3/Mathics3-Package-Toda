AllRelations = {}
AllRelationsTeXReasons = {}
AllRelationsReasons = {}
AllRelationsStatements = {}
ExplainedRelations = {}
ElementDocumentation = ""

Verbosify[rel_,statement_,reason_] :=
 Module[{exrel,STATEMENT,REASON,CONDITION,SOW},
  Off[RuleDelayed::rhs];
  exrel = rel /. Condition -> CONDITION;
  exrel =
   exrel /.
    {Rule[a_,b_] :>
      RuleDelayed[a,(Sow[{a,b,STATEMENT,REASON}]; b)],
     RuleDelayed[a_,CONDITION[b_,c_]] :> 
      RuleDelayed[a,CONDITION[(Sow[{a /. t_Pattern :> First[t],b,STATEMENT,REASON}]; b),c]],
     RuleDelayed[a_,b_] :>
      RuleDelayed[a,(Sow[{a /. t_Pattern :> First[t],b,STATEMENT,REASON}]; b)]
    };
  exrel = exrel /. CONDITION -> Condition
                /. {STATEMENT -> statement,
                    REASON -> reason,
                    SOW -> Sow};
  On[RuleDelayed::rhs];
  exrel
 ]

AddRelation[rel_,reason_] :=
 Module[{mreason,exrel,state,MREASON},
  AllRelations = Join[AllRelations,{rel}];
  AllRelationsTeXReasons = Join[AllRelationsTeXReasons,{reason}];
  mreason = TeXToMath[reason];
  If[Head[rel] === RuleDelayed,
   state = ToString[InputForm[rel]],
  (* Else *)
   state = ""
  ];
  AllRelationsReasons = Join[AllRelationsReasons,{mreason}];
  AllRelationsStatements = 
   Join[AllRelationsStatements,{state}];
  ExplainedRelations =
   Join[ExplainedRelations,{Verbosify[rel,state,mreason]}];
 ]

AddRelation[rel_,state_,reason_] :=
 Module[{mreason,exrel,STATE,MREASON},
  AllRelations = Join[AllRelations,{rel}];
  AllRelationsTeXReasons = Join[AllRelationsTeXReasons,{reason}];
  mreason = TeXToMath[reason];
  AllRelationsReasons = Join[AllRelationsReasons,{mreason}];
  AllRelationsStatements = 
   Join[AllRelationsStatements,{state}];
  ExplainedRelations =
   Join[ExplainedRelations,{Verbosify[rel,state,mreason]}];
 ]

Zop[x_] := 
 Module[{y},
  y = Expand[x] //. AllRelations;
  If[ Length[y] > 0,
   y = (# //. AllRelations) & /@ y;];
  y
 ]

Zap[x_] := FixedPoint[Zop,x]


