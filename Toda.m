RawShowMap[F_,k_Integer,n_Integer] := 
 Module[{l,m,src,tgt,gens,act},
  l = SourceShift[F][k];
  m = TargetShift[F][n];
  src = SpherePi[k,n];
  If[Head[src] =!= Group,
   Return[
    SequenceForm[
     "The source group ",
     SubsuperscriptBox["\[Pi]",k,n],
     " is not known."]]];
  tgt = SpherePi[l,m];
  If[Head[tgt] =!= Group,
   Return[
    SequenceForm[
     "The target group ",
     SubsuperscriptBox["\[Pi]",l,m],
     " is not known."]]];
  gens = Generators[src];
  act = {Format[#],"\[RightTeeArrow]",Format[Zap[F[#]]]} & /@ gens;
  GridBox[
   Join[
   {{SubsuperscriptBox["\[Pi]", k, n], 
     OverscriptBox["\[RightArrow]", Format[F]], 
     SubsuperscriptBox["\[Pi]", l, m]},
    {SpherePi[k,n],"",SpherePi[l,m]}},
   act
   ]]
 ]

ShowMap[F_,s_Integer,t_Integer] := 
 DisplayForm[RawShowMap[F,s,t]]

ShowMap[F_,a_] := 
 Module[{s,t,A},
  s = SourceSphere[a];
  t = TargetSphere[a];
  A = First[RawShowMap[F,s,t]];
  If[Not[MemberQ[Generators[SpherePi[s,t]],a]],
   A = Join[A,{{Format[x],"\[RightTeeArrow]",Zap[F[x]]}}]
  ];
  DisplayForm[GridBox[A]]
 ] /;  SphereQ[Source[a]] && SphereQ[Target[a]];

ShowMap[F_,From[x__]] := ShowMap[F,x]

ShowMap[F_,To[l_Integer,m_Integer]] := 
 Module[{k,n,kk,nn},
  k = kk /. First[Solve[SourceShift[F][kk] == l,kk]];
  n = nn /. First[Solve[TargetShift[F][nn] == m,nn]];
  ShowMap[F,k,n]
 ]

ShowMap[F_,To[a_]] := 
 ShowMap[F,To[SourceSphere[a],TargetSphere[a]]] /;
  SphereQ[Source[a]] && SphereQ[Target[a]];
 


