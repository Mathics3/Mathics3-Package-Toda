Sigma::usage =
 TeXToMath["\\(\\Sigma\\) is the suspension functor. "]

Format[Sigma] = \[CapitalSigma]

Format[Sigma[a_]] := SequenceForm[\[CapitalSigma],a]

Sigma[Sphere[n_]] := Sphere[n+1]

SourceShift[Sigma] = (#+1) & 
TargetShift[Sigma] = (#+1) & 

Source[Sigma[a_]]       := Sigma[Source[a]]
Target[Sigma[a_]]       := Sigma[Target[a]]

Sigma[l_List]           := Sigma /@ l
Sigma[A_Group]          := Sigma /@ Generators[A]
Sigma[0]                 = 0
Sigma[a_Plus]           := Sigma /@ a
Sigma[n_Integer a_]     := Expand[n Sigma[a]]
Sigma[Coset[a_,B_List]] := Coset[Sigma[a],Sigma /@ B]
Sigma[a_o]              := Sigma /@ a
Sigma[w[_]]             := 0
Sigma[WhiteheadP[_]]    := 0
IsSuspension[_Sigma]    := True
IsSuspension[a_]        := True /; IsDoubleSuspension[a]
IsSuspension[t_o]       := And @@ (IsSuspension /@ (List @@ t))

SigmaIterate[n_Integer,a_] := Nest[Sigma,a,n]

