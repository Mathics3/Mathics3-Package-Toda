MaximalDesuspensions[a_] :=
 Module[{tgt,stem,t,A,B},
  tgt = TargetSphere[a];
  stem = Stem[a];
  t = tgt+1;
  B = {a};
  While[B =!= {},
   t = t-1;
   A = B;
   G = TorsionSubgroup[SpherePi[t+stem-1,t-1]];
   B = Select[Elements[G],
	      MemberQ[A,Zap[Sigma[#]]] &];
  ];
  A 
 ]

FindGenealogy[a_] :=
 Module[{n},
  n = TargetSphere[a];
  GenealogySort[Stem[a],
   Union[GenealogyName /@ Zap[Hopf /@ MaximalDesuspensions[a]]] /.
       x[i_,{j___}] :> x[n,{(i-1)/2,j}]
  ]
 ]

ShowGenealogy[a_] := 
 Module[{X,u}, 
  If[Head[GenealogyName[a]] =!= GenealogyName,
   Return[""]
  ];
  X = FindGenealogy[a];
  s = StringJoin["SetGenealogy[", 
	         ToString[InputForm[a]], ",",
	         ToString[InputForm[First[X]]], "]\n"];
  If[Length[X] > 1,
   s = StringJoin[s,"Other possibilities:\n",
        ToString[InputForm[X]],"\n\n"]];
  s
 ]

