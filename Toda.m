AdditiveOrder[_] := Infinity

OrderRule0 = 
 (k_Integer XXXX :> Mod[k,NNNN] XXXX /; k<0 || k>=NNNN)

OrderRule1 = 
 (k_Integer o[a__,XXXX] :> Mod[k,NNNN] o[a,XXXX] /; k<0 || k>=NNNN)

OrderRule2 =
 (k_Integer o[XXXX,b__] :> Mod[k,NNNN] o[XXXX,b] /; (k<0 || k>=NNNN) && IsSuspension[o[b]])

SetOrder[x_,n_,reason_] := 
 Module[{r},
  AdditiveOrder[x] = n;
  r = OrderRule0 /. {XXXX -> x,NNNN -> n};
  AddRelation[r,SequenceForm[n,Format[x],"=0"],reason];
  r = OrderRule1 /. {XXXX -> x,NNNN -> n};
  AddRelation[r,SequenceForm[n,Format[x],"=0"],reason];
  r = OrderRule2 /. {XXXX -> x,NNNN -> n};
  AddRelation[r,SequenceForm[n,Format[x],"=0"],reason];
 ]

StableOrderRule0 = 
 (k_Integer XXXX[m_] :> Mod[k,NNNN] XXXX[m] /;
   (m >= DDDD) && (k<0 || k>=NNNN))

StableOrderRule1 = 
 (k_Integer o[a__,XXXX[m_]] :> Mod[k,NNNN] o[a,XXXX[m]] /;
   (m >= DDDD) && (k<0 || k>=NNNN))

StableOrderRule2 = 
 (k_Integer o[XXXX[m_],b__] :> Mod[k,NNNN] o[XXXX[m],b] /;
   (m >= DDDD) && (k<0 || k>=NNNN) && IsSuspension[o[b]])

SetStableOrder[x_,n_,d_,reason_] := 
 Module[{r},
  AdditiveOrder[Release[x][k_]] := n /; k >= d;
  r = StableOrderRule0 /. {XXXX -> x,NNNN -> n,DDDD -> d};
  AddRelation[r,
   SequenceForm[n,Subscript[x,"k"],"=0 for k \[GreaterEqual] ",d],
   reason];
  r = StableOrderRule1 /. {XXXX -> x,NNNN -> n,DDDD -> d};
  AddRelation[r,
   SequenceForm[n,Subscript[x,"k"],"=0 for k \[GreaterEqual] ",d],
   reason];
  r = StableOrderRule2 /. {XXXX -> x,NNNN -> n,DDDD -> d};
  AddRelation[r,
   SequenceForm[n,Subscript[x,"k"],"=0 for k \[GreaterEqual] ",d],
   reason];
 ]

GeneralOrderRule = 
 (k_Integer XXXX :> Mod[k,NNNN] YYYY /; (k<0 || k>=NNNN) && CCCC)

AddOrderRule[pattern_,n_,criterion_,state_,reason_] :=
 Module[{r,rhs},
  AdditiveOrder[pattern] := n /; criterion;
  rhs = pattern /. {t_Pattern :> First[t],
                    t_PatternTest :> First[t]};
  r = GeneralOrderRule /. {XXXX -> pattern, YYYY -> rhs,
                           NNNN -> n, CCCC -> criterion};
  AddRelation[r,state,reason] 
 ]

