(* If a : S^k -> S^l and b : S^l -> S^m then                            *)
(* Source[a] = Sphere[k], Target[a] = Sphere[l], and o[b,a] is the      *)
(* composite.                                                           *)

Format[t_o] := Infix[t,\[EmptySmallCircle]] /; Length[t] > 1

SetAttributes[o,{Flat,OneIdentity}]

o[a_, b_] := Uncomposable /;
 SphereQ[Source[a]] && SphereQ[Target[b]] && Source[a] =!= Target[b]

Source[o[a__,b_]]       := Source[b]
Target[o[a_,b__]]       := Target[a]
Source[n_Integer a_]    := Source[a]
Target[n_Integer a_]    := Target[a]

SourceSphere[a_] := First[Source[a]] /; SphereQ[Source[a]]
TargetSphere[a_] := First[Target[a]] /; SphereQ[Target[a]]

Source[x_Plus] :=
 Module[{l},
  l = Source /@ (List @@ x);
  If[Equal @@ l,First[l],Inhomogeneous]
 ]

Target[x_Plus] :=
 Module[{l},
  l = Target /@ (List @@ x);
  If[Equal @@ l,First[l],Inhomogeneous]
 ]

Source[Coset[0,{y__}]] :=
 Module[{l},
  l = Source /@ {y};
  If[Equal @@ l,First[l],Inhomogeneous]
 ]

Target[Coset[0,{y__}]] :=
 Module[{l},
  l = Target /@ {y};
  If[Equal @@ l,First[l],Inhomogeneous]
 ]

Source[Coset[x_,{y__}]] :=
 Module[{l},
  l = Source /@ {x,y};
  If[Equal @@ l,First[l],Inhomogeneous]
 ]

Target[Coset[x_,{y__}]] :=
 Module[{l},
  l = Target /@ {x,y};
  If[Equal @@ l,First[l],Inhomogeneous]
 ]

Source[PlusOrMinus[x_]] := Source[x]
Target[PlusOrMinus[x_]] := Target[x]

Stem[a_] := 
 Module[{s,t},
  s = Source[a];
  t = Target[a];
  If[s === Inhomogeneous || t === Inhomogeneous,
   Return[Inhomogeneous]
  ];
  If[Head[s] =!= Sphere || Head[t] =!= Sphere,
   Return[Inhomogeneous]
  ];
  First[s] - First[t]
 ]

o[a_,b_Plus]            := o[a,#] & /@ b
o[a_,n_Integer b_]      := Expand[n o[a,b]]
o[a_,n_Integer]         := Expand[n a]
o[a_,Coset[b_,C_List]]  := Coset[o[a,b],o[a,#]& /@ C]
o[a_Plus,b_]            := o[#,b] & /@ a /; IsSuspension[b]
o[n_Integer a_,b_]      := Expand[n o[a,b]] /; IsSuspension[b]
o[n_Integer,b_]         := Expand[n b] /; IsSuspension[b]
o[Coset[a_,B_List],c_]  := Coset[o[a,c],o[#,c] & /@ B] /; IsSuspension[c]
o[a_,_iota]             := a
o[_iota,b_]             := b

o[a_,0]                 := 0
o[0,b_]                 := 0

(* Whitehead, GTM61, Theorem XI.8.9, modulo odd torsion, assuming *)
(* Hilton-Hopf = James-Hopf:                                      *)
o[k_Integer b_,a_] :=
  k o[b,a] + Expand[(k(k-1)/2) o[b,w[SourceSphere[b]],Hopf[a]]] /;
   SphereQ[Source[b]] && SphereQ[Target[b]] && SphereQ[Source[a]]

ST[x_]                  := {SourceSphere[x],TargetSphere[x]}

Home[x_] := HomotopySet[Source[x],Target[x]]

ShowHome[x_]            :=
 Module[{s,t,nm},
  s = Source[x];
  t = Target[x];
  If[Head[s] === Sphere,
   nm = SequenceForm[Subscript[\[Pi],First[s]],t];
   rf = SequenceForm["\n",SpherePiReference[First[s],First[t]]],
   (* Else *)
   nm = SequenceForm["[",s,",",t,"]"];
   rf = "";
  ];
  SequenceForm[nm," = ",HomotopySet[s,t],rf]
 ]

ShowSpherePi[n_,m_] := 
 SequenceForm[
  Subsuperscript["\[Pi]",n,m], " = ",
  SpherePi[n,m],
  "\n(",SpherePiReference[n,m],")\n"
 ]

