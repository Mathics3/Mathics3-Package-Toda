EZop[x_] := 
 Module[{y},
  y = Expand[x] //. ExplainedRelations;
  If[ Length[y] > 0,
   y = (# //. ExplainedRelations) & /@ y;];
  y
 ]

EZap[x_] := FixedPoint[EZop,x]

