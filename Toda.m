(* Genealogy data                                                       *)

gpad[stem_,u_] := 
 (u /. x[n_,J_] :> x[n,Join[J,Table[-1,{stem-Length[J]}]]])

gunpad[u_] := (u /. x[n_,J_] :> x[n,Select[J,Positive]])

GenealogySort[stem_,u_] := gunpad[Sort[gpad[stem,u]]]

GenealogyName[x_Plus] := GenealogyName /@ x
TwoPowerQ[n_Integer] := 
 ((First /@ FactorInteger[2n]) === {2})
TwoAdicValuation[n_Integer] := 
 Select[FactorInteger[2n],First[#] == 2 &][[1,2]] - 1

GenealogyName[n_Integer a_] :=
 Module[{m,b,r,u},
  m = n;
  If[Head[AdditiveOrder[x]] == Integer,
   m = Mod[m,AdditiveOrder[x]]
  ];
  b = IntegerDigits[m,2];
  r = Length[b];
  u = 0;
  Do[
   If[b[[r-i]] == 1,u = u+GenealogyName[2^i a]],
   {i,0,r-1}
  ];
