(* TodaBracket[{a,b,c},n] is the coset that Toda denotes by             *)
(* {a,Sigma^n b,Sigma^n c}_n.  It is defined when a o Sigma^n b = 0 and *)
(* c o b = 0, and it is a coset of                                      *)
(* (Sigma^{n+1} c)^* [Sigma^{n+1}X, Z] + a_* Sigma^n [Sigma W,Y].       *)

Indeterminacy[TodaBracket[u__]] := TodaBracketIndeterminacy[u]

TodaBracketIndeterminacy[x_List, n_] := 
  Module[{a,b,c,W,X,Y,Z,G,H,indet},
      a = x[[1]]; b = x[[2]]; c = x[[3]];
      W = Source[c];
      X = Source[b];
      Y = Target[b];
      Z = Target[a];
      G = HomotopySet[SigmaIterate[n + 1, X], Z];
      H = HomotopySet[Sigma[W], Y];
      indet = 
        Union[o[#, SigmaIterate[n + 1, c]] & /@ Generators[G], 
          o[a, SigmaIterate[n, #]] & /@ Generators[H]];
      indet = Select[indet, # =!= 0 &];
      indet] /; Length[x] == 3

