DeclareFamily[name_,format_,source_,target_,defn_] := 
 Module[{k,ixformat},
  Format[name] = format;
  Format[Release[name][k_]] := Subscript[name,k];
  If[Head[format] == Superscript,
   Format[Release[name][k_]] := Subsuperscript[format[[1]],k,format[[2]]];
  ];
  Release[name][k_] := Undefined /; k < target;
  Source[Release[name][k_]] := Sphere[k - target + source];
  Target[Release[name][k_]] := Sphere[k];
  Sigma[Release[name][k_]]  := name[k+1];
  IsSuspension[Release[name][k_]] := True /; k > target;
  WhiteheadP[Release[name][k_]] :=
   o[w[(k-1)/2],name[k-2]] /; k > target+1 && OddQ[k];
  WhiteheadP[o[a_,name[k_]]] :=
   o[WhiteheadP[a],name[k-2]] /; k > target+1;
  Defn[name] = defn;
  Defn[Release[name][_]] := defn;
  MessageName[name,"usage"]  = TeXToMath[defn];
  If[Head[ElementDocumentation] =!= String,
     ElementDocumentation = ""];
  ElementDocumentation = 
   StringJoin[
    ElementDocumentation,
    "\n\\item ",defn,
    " Mathematica notation is {\\tt ",ToString[InputForm[name]],"[n]}.\n"
   ];
 ]

